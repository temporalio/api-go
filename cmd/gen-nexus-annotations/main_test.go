package main

import (
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"testing"

	"github.com/stretchr/testify/require"
)

func TestGenerateAliases(t *testing.T) {
	const source = `package upstream

type AddedMessage struct{}
type privateMessage struct{}
const AddedValue = 1

// Extension fields for tests.
var (
	// Added extension.
	E_Added = 1
	internal = 2
)

var File_added_proto = 3
`
	file, err := parser.ParseFile(token.NewFileSet(), "added.pb.go", source, parser.ParseComments)
	require.NoError(t, err)
	got, err := generateAliases([]*ast.File{file})
	require.NoError(t, err)
	want, err := format.Source([]byte(`// Code generated by gen-nexus-annotations. DO NOT EDIT.

// Package v1 exposes the upstream Nexus protobuf annotations.
package v1

import upstream "github.com/nexus-rpc/nexus-proto-annotations/go/nexusannotations/v1"

type AddedMessage = upstream.AddedMessage

const AddedValue = upstream.AddedValue

// Extension fields for tests.
var (
	// Added extension.
	E_Added = upstream.E_Added
)

var File_added_proto = upstream.File_added_proto
`))
	require.NoError(t, err)
	require.Equal(t, string(want), string(got))
}
