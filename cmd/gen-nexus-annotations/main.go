package main

import (
	"encoding/json"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

const upstreamPackage = "github.com/nexus-rpc/nexus-proto-annotations/go/nexusannotations/v1"

func main() {
	log.SetFlags(0)
	if len(os.Args) != 2 {
		log.Fatal("usage: gen-nexus-annotations <output>")
	}
	if err := run(os.Args[1]); err != nil {
		log.Fatal(err)
	}
}

func run(output string) error {
	cmd := exec.Command("go", "list", "-json", upstreamPackage)
	cmd.Stderr = os.Stderr
	data, err := cmd.Output()
	if err != nil {
		return fmt.Errorf("listing upstream Nexus annotations: %w", err)
	}
	var pkg struct {
		Dir     string
		GoFiles []string
	}
	if err := json.Unmarshal(data, &pkg); err != nil {
		return fmt.Errorf("decoding upstream package: %w", err)
	}
	fset := token.NewFileSet()
	var files []*ast.File
	for _, name := range pkg.GoFiles {
		if !strings.HasSuffix(name, ".pb.go") {
			continue
		}
		file, err := parser.ParseFile(fset, filepath.Join(pkg.Dir, name), nil, parser.ParseComments)
		if err != nil {
			return fmt.Errorf("parsing upstream binding: %w", err)
		}
		files = append(files, file)
	}
	aliases, err := generateAliases(files)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(output), 0755); err != nil {
		return err
	}
	return os.WriteFile(output, aliases, 0644)
}

func generateAliases(files []*ast.File) ([]byte, error) {
	var body strings.Builder
	for _, file := range files {
		for _, node := range file.Decls {
			decl, ok := node.(*ast.GenDecl)
			if !ok || decl.Tok == token.IMPORT {
				continue
			}
			var specs strings.Builder
			for _, node := range decl.Specs {
				names, doc := declarationNames(node)
				for _, name := range names {
					if !name.IsExported() {
						continue
					}
					writeComments(&specs, doc)
					doc = nil
					fmt.Fprintf(&specs, "%s = upstream.%s\n", name.Name, name.Name)
				}
			}
			if specs.Len() == 0 {
				continue
			}
			writeComments(&body, decl.Doc)
			if decl.Lparen.IsValid() {
				fmt.Fprintf(&body, "%s (\n%s)\n\n", decl.Tok, specs.String())
			} else {
				fmt.Fprintf(&body, "%s %s\n", decl.Tok, specs.String())
			}
		}
	}
	if body.Len() == 0 {
		return nil, fmt.Errorf("no exported declarations in upstream Nexus protobuf bindings")
	}
	header := fmt.Sprintf(`// Code generated by gen-nexus-annotations. DO NOT EDIT.

// Package v1 exposes the upstream Nexus protobuf annotations.
package v1

import upstream %q

`, upstreamPackage)
	return format.Source([]byte(header + body.String()))
}

func declarationNames(spec ast.Spec) ([]*ast.Ident, *ast.CommentGroup) {
	switch spec := spec.(type) {
	case *ast.TypeSpec:
		return []*ast.Ident{spec.Name}, spec.Doc
	case *ast.ValueSpec:
		return spec.Names, spec.Doc
	default:
		return nil, nil
	}
}

func writeComments(output *strings.Builder, group *ast.CommentGroup) {
	if group != nil {
		for _, comment := range group.List {
			fmt.Fprintln(output, comment.Text)
		}
	}
}
